export function filterProducts(
  products: Product[],
  filters: { categories: string[]; protectionTypes: string[] }
) {
  return products.filter(p => {
    const catOk = filters.categories.length === 0 || filters.categories.includes(p.category)
    const protOk = filters.protectionTypes.length === 0 || p.protectionTypes.some(t => filters.protectionTypes.includes(t))
    return catOk && protOk
  })
}
